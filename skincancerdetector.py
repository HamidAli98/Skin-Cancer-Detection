"""### Visualizing Misclassified Test Images
To analyze the types of errors our model is making, we will identify the images from the test set where the model's predicted probability did not match the actual binary label (using a threshold of 0.5).
"""

import matplotlib.pyplot as plt
from PIL import Image
import os

# 1. Collect predictions and actual images/labels
test_images = []
test_labels_list = []
test_preds_list = []

# Iterate through the test dataset
for imgs, labels in test_ds:
    preds = model.predict(imgs, verbose=0)
    test_images.append(imgs.numpy())
    test_labels_list.append(labels.numpy())
    test_preds_list.append(preds)

# Concatenate everything
test_images = np.concatenate(test_images, axis=0)
test_labels_list = np.concatenate(test_labels_list, axis=0)
test_preds_list = np.concatenate(test_preds_list, axis=0).flatten()

# Binary threshold predictions at 0.5
predicted_classes = (test_preds_list >= 0.5).astype(np.float32)

# Identify misclassified indices
misclassified_indices = np.where(predicted_classes != test_labels_list)[0]
print(f"Total test images: {len(test_labels_list)}")
print(f"Number of misclassified images: {len(misclassified_indices)}")

# 2. Plot the misclassified images
if len(misclassified_indices) > 0:
    num_cols = min(4, len(misclassified_indices))
    num_rows = (len(misclassified_indices) + num_cols - 1) // num_cols
    fig, axes = plt.subplots(num_rows, num_cols, figsize=(15, 4 * num_rows))

    # Handle case where subplots returns a single axis instead of an array
    if len(misclassified_indices) == 1:
        axes = np.array([axes])

    for idx, test_idx in enumerate(misclassified_indices):
        ax = axes.flat[idx] if hasattr(axes, 'flat') else axes[idx]

        # Retrieve original path to display filename
        original_path = paths_test[test_idx]
        filename = os.path.basename(original_path)

        # Show the image
        ax.imshow(test_images[test_idx])
        ax.set_title(f"File: {filename}\nTrue: {int(test_labels_list[test_idx])} | Pred: {test_preds_list[test_idx]:.2f}", fontsize=10)
        ax.axis('off')

    # Hide any unused subplots
    if hasattr(axes, 'flat'):
        for ax in axes.flat[len(misclassified_indices):]:
            ax.axis('off')

    plt.suptitle("Misclassified Test Images Analysis", fontsize=16, y=1.02)
    plt.tight_layout()
    plt.show()
else:
    print("Excellent! No misclassified images found in the test set.")

